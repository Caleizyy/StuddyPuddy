import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FIRST_SEED, RANDOM_CASES, runCorrectnessChecks, toMarkdown } from './run.js';

const rows = runCorrectnessChecks();
const table = toMarkdown(rows);
console.log(table);

if (process.argv.includes('--write')) {
  const here = dirname(fileURLToPath(import.meta.url));
  const target = resolve(here, '../../../docs/verification-correctness.md');
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(
    target,
    `# Correctness check: results\n\n` +
      `Generated by \`npm run verify:correctness -- --write\`. See the main README for what is checked.\n` +
      `Random inputs: ${RANDOM_CASES} cases, seeds ${FIRST_SEED} to ${FIRST_SEED + RANDOM_CASES - 1}, ` +
      `fixed "today" of 2026-11-09, so the run is repeatable.\n\n${table}\n`,
  );
  console.log(`\nSaved to ${target}`);
}

if (rows.some((row) => !row.passed)) {
  console.error('\nCorrectness check FAILED');
  process.exit(1);
}
console.log('\nCorrectness check passed');
